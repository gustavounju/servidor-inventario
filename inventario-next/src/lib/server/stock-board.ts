export async function loadStockBoard({
	query = '',
	state = '',
	type = '',
	limit = 120
}: {
	query?: string;
	state?: string;
	type?: string;
	limit?: number;
} = {}): Promise<StockBoard> {
	const trimmedQuery = query.trim();
	const trimmedState = state.trim() as StockState | '';
	const trimmedType = type.trim();
	if (!appConfig.MYSQL_PASSWORD)
		return demoStockBoard({ query: trimmedQuery, state: trimmedState, type: trimmedType });

	const pool = getMysqlPool();
	const likeQuery = `%${trimmedQuery}%`;
	const [rows] = await pool.query<ComponentRow[]>(
		`
		SELECT
			id, serial_number, component_type, brand_model, status, lifecycle_status,
			assigned_pc, assigned_user, assigned_fuero, supplier, invoice_number,
			oc_number, kit_name, patrimonio_code, created_at, build_order_id,
			is_autogenerated_id
		FROM components
		WHERE (? = '' OR component_type = ?)
		  AND (
			? = ''
			OR serial_number LIKE ?
			OR component_type LIKE ?
			OR brand_model LIKE ?
			OR supplier LIKE ?
			OR invoice_number LIKE ?
			OR oc_number LIKE ?
			OR assigned_pc LIKE ?
			OR assigned_user LIKE ?
			OR assigned_fuero LIKE ?
			OR kit_name LIKE ?
			OR patrimonio_code LIKE ?
		  )
		ORDER BY created_at DESC, component_type ASC, brand_model ASC
		LIMIT ?
		`,
		[
			trimmedType,
			trimmedType,
			trimmedQuery,
			likeQuery,
			likeQuery,
			likeQuery,
			likeQuery,
			likeQuery,
			likeQuery,
			likeQuery,
			likeQuery,
			likeQuery,
			likeQuery,
			likeQuery,
			limit * 3
		]
	);
	const allComponents = rows.map(rowToComponent);
	const components = filterComponents(allComponents, '', trimmedState, '').slice(0, limit);

	return {
		mode: 'mysql',
		query: trimmedQuery,
		state: trimmedState,
		type: trimmedType,
		components,
		types: typesFromComponents(allComponents),
		states: STOCK_STATES,
		summary: summarize(components),
		note: appConfig.MYSQL_READ_ONLY
			? 'MySQL conectado en modo lectura.'
			: 'MySQL conectado con escritura habilitada por configuracion.'
	};
}
