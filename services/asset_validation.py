"""
asset_validation.py — Servicio de validación del Gemelo Digital Patrimonial.

Lógica central del Sistema Patrimonial:
  - Dado un pc_name, determina si la PC reportada por el script .ps1
    tiene un activo registrado en components y si el hardware coincide.

Valores de validation_status:
  'sin_gemelo'   → El script reportó esta PC pero no hay componente CPU asignado.
  'pendiente'    → Se asignó un CPU (Build Order o asignación directa) pero el script
                   no ha reportado desde esa asignación (last_report vacío o None).
  'validado'     → El hardware reportado coincide con el activo registrado.
  'discrepancia' → El hardware cambió respecto al activo registrado (posible
                   reemplazo sin documentar).

Este módulo NO modifica la tabla pcs; solo calcula el estado.
La escritura la hace el caller (bp_api.py → process_inventory_data).
"""

import logging
import re

logger = logging.getLogger(__name__)

_IGNORED_STORAGE_TOKENS = (
    "USB SD READER", "USB MS READER", "USB SM READER", "USB CF READER",
    "CARD READER USB DEVICE", "GENERIC USB STORAGE", "USB CR READER",
    "SD/MMC CARD READER", "USB DEVICE", "USB FLASH", "PENDRIVE",
    "DATATRAVELER", "CRUZER", "CARD READER", "CARD_READER",
    "MS READER", "SD READER", "CF READER", "SM READER", "SD/MMC CARD",
)


def is_ignored_storage_device(value: str) -> bool:
    """Indica si WMI describió un lector/medio USB que no es disco patrimonial."""
    normalized = str(value or "").upper()
    if not normalized:
        return False
    if any(marker in normalized for marker in ("(0GB)", "(0.00GB)", "0.0 GB", " 0GB")):
        return True
    return any(token in normalized for token in _IGNORED_STORAGE_TOKENS)


def is_ignored_storage_component(component) -> bool:
    """Aplica la exclusión solo a componentes que representan almacenamiento."""
    if not component:
        return False
    component_type = str(component.get("component_type") or "").upper()
    is_storage = any(token in component_type for token in ("DISCO", "SSD", "HDD", "ALMACEN"))
    return is_storage and is_ignored_storage_device(component.get("brand_model"))

# ─────────────────────────────────────────────────────────────────────────────
# Helpers de normalización (locales para evitar importar bp_api)
# ─────────────────────────────────────────────────────────────────────────────

def _normalize_hw_token(value: str) -> str:
    """Limpia un string de hardware para comparación tolerante a cambios menores."""
    if not value:
        return ""
    v = value.strip().upper()
    # Eliminar sufijos de velocidad / revisiones que no identifican el modelo
    v = re.sub(r"\s*@\s*[\d.]+\s*GHZ", "", v)
    v = re.sub(r"\s+REV\s*[\d.]+", "", v)
    # Eliminar prefijos de número de serie habituales como SN:, S/N:, UUID:
    v = re.sub(r"\[?\b(SN|S/N|SERIAL|UUID)\b\s*:\s*", "", v)
    # Reemplazar corchetes, paréntesis, comas y barras por espacios para evitar fallos por puntuación
    v = re.sub(r"[\[\]\(\)\,\;\|]", " ", v)
    v = re.sub(r"\s+", " ", v)
    return v.strip()


def _normalize_hw_identity(value: str) -> str:
    """Normaliza modelo para detectar filas sombra aunque difieran S/N o capacidad."""
    v = str(value or "").strip().upper()
    if not v:
        return ""
    v = re.sub(r"[\[\(]\s*(SN|S/N|SERIAL|UUID)\s*:\s*[^\]\)]+[\]\)]", " ", v)
    v = re.sub(r"\bSN\s*:\s*\S+", " ", v)
    v = re.sub(r"\(\s*\d+(?:\.\d+)?\s*GB\s*\)", " ", v)
    v = re.sub(r"\b\d+(?:\.\d+)?\s*GB\b", " ", v)
    v = _normalize_hw_token(v)
    return v


def _is_autogenerated_component(component) -> bool:
    serial = str(component.get("serial_number") or "").strip().upper()
    return bool(component.get("is_autogenerated_id")) or serial.startswith("INT-")


def _component_identity_key(component):
    return _normalize_hw_identity(component.get("brand_model"))


def _dedupe_validation_components(components):
    """Oculta componentes INT-* sombra antes de armar la comparación patrimonial."""
    result = []
    for component in components or []:
        current = dict(component)
        current_family = _normalize_component_type(current.get("component_type"))
        current_identity = _component_identity_key(current)
        if not current_identity:
            result.append(current)
            continue

        shadowed = False
        for idx, existing in enumerate(result):
            existing_family = _normalize_component_type(existing.get("component_type"))
            if existing_family != current_family:
                continue
            existing_identity = _component_identity_key(existing)
            equivalent = (
                existing_identity
                and (
                    existing_identity == current_identity
                    or existing_identity in current_identity
                    or current_identity in existing_identity
                )
            )
            if not equivalent:
                continue
            existing_auto = _is_autogenerated_component(existing)
            current_auto = _is_autogenerated_component(current)
            if existing_auto and not current_auto:
                result[idx] = current
            shadowed = True
            break

        if not shadowed:
            result.append(current)
    return result


def filter_ignore_devices(disk_str: str) -> str:
    """
    Filtra lectores de tarjetas USB (0GB, SD/MS/CF readers) de la cadena de discos
    para evitar falsas discrepancias en la auditoría del gemelo digital.
    """
    if not disk_str or disk_str == "Sin reporte de script":
        return disk_str or ""
    
    parts = [p.strip() for p in str(disk_str).split("|") if p.strip()]
    cleaned = []
    
    for p in parts:
        if is_ignored_storage_device(p):
            continue
        cleaned.append(p)
        
    return " | ".join(cleaned)


def _hw_tokens_match(a: str, b: str) -> bool:
    """Compara dos strings de hardware normalizados."""
    na, nb = _normalize_hw_token(a), _normalize_hw_token(b)
    if not na or not nb:
        return False
    # Coincidencia exacta o una como substring de la otra (cubre modelos abreviados)
    return na == nb or na in nb or nb in na


def _normalize_component_type(component_type: str) -> str:
    return (component_type or "").strip().lower()


def _extract_ram_total_gb(components, fallback_ram=None) -> float:
    total_stock_gb = 0.0
    for component in components:
        raw_value = f"{component.get('brand_model') or ''} {component.get('component_type') or ''}"
        match = re.search(r"(\d+(?:\.\d+)?)\s*GB", raw_value, re.IGNORECASE)
        if match:
            total_stock_gb += float(match.group(1))
    if total_stock_gb > 0:
        return total_stock_gb
    try:
        return float(fallback_ram or 0)
    except (TypeError, ValueError):
        return 0.0


def _extract_telemetry_ram_gb(script_ram) -> float:
    match = re.search(r"[\d.]+", str(script_ram or ""))
    return float(match.group()) if match else 0.0


def _ram_matches(components, script_ram, fallback_ram=None) -> bool:
    total_stock_gb = _extract_ram_total_gb(components, fallback_ram=fallback_ram)
    telem_gb = _extract_telemetry_ram_gb(script_ram)
    if total_stock_gb <= 0 or telem_gb <= 0:
        return False

    diff = abs(total_stock_gb - telem_gb)
    if diff <= 2.25 or round(telem_gb) == round(total_stock_gb) or int(round(telem_gb)) == int(total_stock_gb):
        return True

    for tier in [2, 4, 8, 16, 32, 64, 128]:
        if telem_gb <= tier and (tier - telem_gb) <= (tier * 0.35) and total_stock_gb == tier:
            return True
    return False


def _split_hardware_entries(raw_value: str):
    return [part.strip() for part in str(raw_value or "").split("|") if part.strip()]


def _storage_matches(components, script_disks, fallback_disks=None) -> bool:
    registered_entries = []
    if components:
        registered_entries = [str(component.get("brand_model") or "").strip() for component in components if str(component.get("brand_model") or "").strip()]
    elif fallback_disks:
        registered_entries = _split_hardware_entries(filter_ignore_devices(fallback_disks))

    telemetry_entries = _split_hardware_entries(filter_ignore_devices(script_disks))
    if not registered_entries or not telemetry_entries:
        return False

    return (
        all(any(_hw_tokens_match(reg_entry, telemetry_entry) for telemetry_entry in telemetry_entries) for reg_entry in registered_entries)
        and all(any(_hw_tokens_match(telemetry_entry, reg_entry) for reg_entry in registered_entries) for telemetry_entry in telemetry_entries)
    )


def resolve_effective_validation_status(
    validation_status: str,
    has_official_components=False,
    has_discrepancies=False,
) -> str:
    """Corrige para la vista un `sin_gemelo` obsoleto usando patrimonio real."""
    normalized = (validation_status or "sin_gemelo").strip().lower()
    if normalized == "sin_gemelo" and has_official_components:
        return "discrepancia" if has_discrepancies else "validado"
    return normalized


def resolve_build_order_action(
    validation_status: str,
    linked_bo=None,
    has_discrepancies=False,
    has_official_components=False,
) -> str:
    """Decide la acción patrimonial sin crear órdenes duplicadas.

    Un equipo que ya tiene gemelo conserva su historia aunque no se haya podido
    localizar una orden antigua. Una orden nueva solo corresponde a un equipo
    realmente sin gemelo. Si ya existe una orden, las diferencias se agregan a
    esa misma orden.
    """
    if linked_bo:
        return "update" if has_discrepancies else "history"
    return "create"


